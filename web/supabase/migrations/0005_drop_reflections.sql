-- 0005_drop_reflections.sql
-- ============================================================
-- 移除「今晚反思」功能
--
-- 背景：
-- V0 把每日反思作为定时推送验证过，使用频次低于预期；
-- 决策直接下线该功能，避免每天 LLM 成本与维护负担。
--
-- 影响：
-- - 不再有 reflections 表的任何读写
-- - 已生成的反思数据会随表一起删除（不可恢复）
-- ============================================================

drop table if exists public.reflections cascade;
